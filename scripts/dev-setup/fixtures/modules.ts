// ── Content builders (shapes from src/lib/validations/module.ts) ──────

/* `variant` picks which real generated PDF the row points at. fileSize and pageCount are
   read off the actual bytes/pages, so what the module list shows always matches what
   opening the file shows. */
const pdf = (variant: 'syllabus' | 'notes', fileName: string) => {
  const source = variant === 'syllabus' ? SYLLABUS : LECTURE_NOTES
  const filePath = variant === 'syllabus' ? SYLLABUS_PDF_PATH : LECTURE_NOTES_PDF_PATH
  return {
    fileType: 'pdf',
    fileName,
    fileSize: String(source.bytes.length),
    /* A real object, so the row is openable → a button, a tab stop, and the viewer and
       download both work. The displayed fileName is free to differ from the stored
       object's name; that is exactly how the real upload path behaves. */
    filePath,
    extraction: { status: 'completed', metadata: { pageCount: source.pageCount } },
  }
}
const deck = (fileName: string, mb = 8.2) => ({
  fileType: 'ppt',
  fileName,
  fileSize: String(Math.round(mb * 1_000_000)),
})
const video = (videoUrl: string, minutes: number) => ({
  videoUrl,
  provider: 'youtube',
  duration: minutes,
})
const note = (body: string) => ({ body })
const paper = (url: string, venue: string, venueId: string) => ({
  url,
  referenceType: 'paper',
  venue,
  venueId,
})

