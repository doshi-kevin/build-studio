// Shared module/PDF fixture — a REALISTIC spread of modules, dividers and items for one
// course section. Used by both the canonical intern seed (seed-dev.ts) and the standalone
// seed-modules-tile-fixtures.ts (which targets an arbitrary section for UI dev work).
//
// The fixture is deliberately awkward, not tidy. It includes the cases that break layouts:
//   - rows of 2, 3 and 4 modules (dividers end a row, so row length varies)
//   - a very long filename + a long description, to find truncation/clamping
//   - a module with NO items (the "Empty" summary and the empty-panel copy)
//   - a module with no week_number (the tile has no eyebrow to align to)
//   - a module holding an in-module section_divider item (full width inside the panel)
//   - two locked weeks, whose items must never reach the browser
//
// PDF lecture items point at REAL, genuinely multi-page objects in the course-materials
// bucket (generated by fixtures/pdf.ts — a real syllabus and a real set of lecture notes,
// both 3 real pages, uploaded once and shared). This matters for more than the viewer: a
// row with no file isn't openable, so StudentModuleItemRow renders it as a div rather
// than a button — deliberately, see its header — and it never becomes a tab stop. It also
// means the displayed page count is TRUE — earlier this fixture reused a 1-page test file
// with a fabricated page-count label, which read as a bug the first time someone opened
// one (a module claiming "47 pages" that opened to 1).
//
// Decks, notes and dividers deliberately keep NO file: a deck whose upload never happened
// is a real state worth seeing, and pointing a `.ppt` row at PDF bytes would make the
// viewer look broken for the wrong reason.
//
// Idempotent: every row has a deterministic uuid derived from its slug, so a re-run
// replaces this fixture's own rows and leaves anything built by hand untouched.

import { type SupabaseClient } from '@supabase/supabase-js'
import { v5 as uuidv5 } from 'uuid'
import { generateLectureNotes, generateSyllabus } from './pdf'

const NS = uuidv5('scholera-dev-modules-tile-fixtures', uuidv5.DNS)
// Scoped by section: two sections seeding this same fixture must get independent rows,
// not collide on one shared id and steal each other's modules (bug caught in testing —
// unscoped ids meant seeding a second section MOVED the rows instead of copying them).
const idFor = (sectionId: string, slug: string) => uuidv5(`${sectionId}:${slug}`, NS)

const days = (n: number) => new Date(Date.now() + n * 86_400_000).toISOString()

