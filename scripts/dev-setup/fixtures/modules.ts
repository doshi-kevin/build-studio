export interface ModuleFixtureResult {
  moduleCount: number
  lockedCount: number
  dividerCount: number
  itemCount: number
}

/** Seeds the fixture above into one section. Callers own resolving/validating the
 *  section (existence, enabledFeatures) — this only writes rows and uploads the PDF. */
export async function seedModuleFixtures(
  supabase: SupabaseClient,
  { sectionId, institutionId }: { sectionId: string; institutionId: string },
): Promise<ModuleFixtureResult> {
  const moduleIds = FIXTURE.filter((e) => e.kind === 'module').map((e) => idFor(sectionId, e.slug))
  const dividerIds = FIXTURE.filter((e) => e.kind === 'divider').map((e) => idFor(sectionId, e.slug))

  // Clear only OUR rows (items cascade from modules), so a re-run replaces this fixture
  // and leaves anything built by hand untouched.
  const [{ error: delMod }, { error: delDiv }] = await Promise.all([
    supabase.from('modules').delete().in('id', moduleIds),
    supabase.from('module_dividers').delete().in('id', dividerIds),
  ])
  if (delMod) throw delMod
  if (delDiv) throw delDiv

  // Append after whatever is already there. Modules and dividers SHARE one position
  // scale — that shared order is what the page and the roadmap both read.
  const [{ data: lastMod }, { data: lastDiv }] = await Promise.all([
    supabase.from('modules').select('position').eq('section_id', sectionId).order('position', { ascending: false }).limit(1),
    supabase.from('module_dividers').select('position').eq('section_id', sectionId).order('position', { ascending: false }).limit(1),
  ])
  const base = Math.max(lastMod?.[0]?.position ?? -1, lastDiv?.[0]?.position ?? -1) + 1

  const moduleRows: Record<string, unknown>[] = []
  const dividerRows: Record<string, unknown>[] = []
  const itemRows: Record<string, unknown>[] = []

  FIXTURE.forEach((entry, i) => {
    const position = base + i
    if (entry.kind === 'divider') {
      dividerRows.push({
        id: idFor(sectionId, entry.slug),
        // module_dividers is tenant-scoped in its own right, unlike modules (which
        // inherit tenancy through section_id).
        institution_id: institutionId,
        section_id: sectionId,
        title: entry.title,
        position,
      })
      return
    }
    moduleRows.push({
      id: idFor(sectionId, entry.slug),
      section_id: sectionId,
      title: entry.title,
      description: entry.description ?? '',
      week_number: entry.week ?? null,
      position,
      is_published: true,
      unlock_date: entry.unlockDate ?? null,
      // Never seeded: private teaching commentary is exactly what the student page's
      // explicit column list exists to keep out of the browser payload.
      instructor_note: '',
    })
    ;(entry.items ?? []).forEach((item, j) => {
      itemRows.push({
        id: idFor(sectionId, item.slug),
        module_id: idFor(sectionId, entry.slug),
        item_type: item.type,
        title: item.title,
        description: item.description ?? '',
        content: item.content,
        position: j,
        is_visible: true,
      })
    })
  })

  // Upload before the items reference them. upsert so re-runs are cheap and so a
  // half-finished earlier run can't leave rows pointing at nothing.
  const [{ error: upSyllabusErr }, { error: upNotesErr }] = await Promise.all([
    supabase.storage
      .from(BUCKET)
      .upload(SYLLABUS_PDF_PATH, SYLLABUS.bytes, { contentType: 'application/pdf', upsert: true }),
    supabase.storage
      .from(BUCKET)
      .upload(LECTURE_NOTES_PDF_PATH, LECTURE_NOTES.bytes, { contentType: 'application/pdf', upsert: true }),
  ])
  if (upSyllabusErr) throw upSyllabusErr
  if (upNotesErr) throw upNotesErr

  const { error: modErr } = await supabase.from('modules').insert(moduleRows)
  if (modErr) throw modErr
  const { error: divErr } = await supabase.from('module_dividers').insert(dividerRows)
  if (divErr) throw divErr
  const { error: itemErr } = await supabase.from('module_items').insert(itemRows)
  if (itemErr) throw itemErr

  return {
    moduleCount: moduleRows.length,
    lockedCount: moduleRows.filter((m) => m.unlock_date).length,
    dividerCount: dividerRows.length,
    itemCount: itemRows.length,
  }
}
