// Builds public/studio-runtime/v1/vendor.js: React, React DOM and the plugin kit, as one
// classic script that defines the frozen `ScholeraKit` global.
//
// Run only when deliberately changing the kit for a NEW bridge version. v1's file is
// pinned (rule 8.7): its sha256 is recorded in src/lib/studio/kit/vendor-hash.ts, and
// studio-validator.test.ts fails if the committed file and the hash disagree.
//
//   node scripts/studio/build-runtime-vendor.mjs
import { createHash } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const repo = join(dirname(fileURLToPath(import.meta.url)), '..', '..')

const result = await build({
  entryPoints: [join(repo, 'src/lib/studio/kit/vendor-entry.tsx')],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  minify: true,
  legalComments: 'inline',
  jsx: 'automatic',
  define: { 'process.env.NODE_ENV': '"production"' },
  tsconfig: join(repo, 'tsconfig.json'),
  write: false,
  logLevel: 'error',
})

const banner = '/* Scholera Studio runtime vendor v1: React, React DOM and the plugin kit. Generated by scripts/studio/build-runtime-vendor.mjs. Do not edit. */\n'
const code = banner + result.outputFiles[0].text
writeFileSync(join(repo, 'public/studio-runtime/v1/vendor.js'), code)

const sha = createHash('sha256').update(code).digest('hex')
writeFileSync(
  join(repo, 'src/lib/studio/kit/vendor-hash.ts'),
  `// Generated by scripts/studio/build-runtime-vendor.mjs. The sha256 of the committed\n// public/studio-runtime/v1/vendor.js. Pinned: v1 never changes (rule 8.7).\nexport const VENDOR_V1_SHA256 = '${sha}'\n`,
)
console.log(`vendor.js ${(code.length / 1024).toFixed(1)} KiB, sha256 ${sha}`)
