// Builds public/studio-runtime/<version>/vendor.js: React, React DOM and that version's
// plugin kit, as one classic script that defines the frozen `ScholeraKit` global.
//
// Run only when deliberately changing the kit of a bridge version that hasn't been
// released. A released version's file is pinned (rule 8.7): its sha256 is recorded in
// src/lib/studio/kit/vendor-hash.ts, and studio-validator.test.ts fails if the committed
// file and the hash disagree. v1 is released and frozen, so this refuses to rebuild it.
//
//   node scripts/studio/build-runtime-vendor.mjs v2
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const repo = join(dirname(fileURLToPath(import.meta.url)), '..', '..')

const ENTRIES = { v2: 'src/lib/studio/kit/v2/vendor-entry.tsx' }
const FROZEN = ['v1']

const version = process.argv[2]
if (FROZEN.includes(version)) {
  console.error(`${version} is released and pinned (rule 8.7). Its vendor.js never changes.`)
  process.exit(1)
}
if (!Object.hasOwn(ENTRIES, version)) {
  console.error(`Usage: node scripts/studio/build-runtime-vendor.mjs <${Object.keys(ENTRIES).join(' | ')}>`)
  process.exit(1)
}

const result = await build({
  entryPoints: [join(repo, ENTRIES[version])],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  minify: true,
  legalComments: 'inline',
  jsx: 'automatic',
  define: { 'process.env.NODE_ENV': '"production"' },
  tsconfig: join(repo, 'tsconfig.json'),
  write: false,
  logLevel: 'error',
})

const banner = `/* Scholera Studio runtime vendor ${version}: React, React DOM and the plugin kit. Generated by scripts/studio/build-runtime-vendor.mjs. Do not edit. */\n`
const code = banner + result.outputFiles[0].text
writeFileSync(join(repo, `public/studio-runtime/${version}/vendor.js`), code)

// Replace this version's pin and keep every other line, so v1's hash is never rewritten.
const sha = createHash('sha256').update(code).digest('hex')
const hashFile = join(repo, 'src/lib/studio/kit/vendor-hash.ts')
const name = `VENDOR_${version.toUpperCase()}_SHA256`
const line = `export const ${name} = '${sha}'`
const current = readFileSync(hashFile, 'utf8')
const pattern = new RegExp(`^export const ${name} = '[0-9a-f]{64}'$`, 'm')
writeFileSync(hashFile, pattern.test(current) ? current.replace(pattern, line) : `${current.trimEnd()}\n${line}\n`)
console.log(`${version}/vendor.js ${(code.length / 1024).toFixed(1)} KiB, sha256 ${sha}`)
