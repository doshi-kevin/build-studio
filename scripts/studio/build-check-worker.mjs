// Builds src/lib/studio/builder/check-worker.generated.ts: the builder's check worker
// (compile and typecheck) as one CommonJS script held in a string, which
// check-worker.ts starts with `new Worker(source, { eval: true })`. That way the worker
// needs no file of its own in the standalone output, and `typescript` stays the one
// external it requires (it is already traced, as a serverExternalPackage).
//
// Run after changing anything the worker bundles: builder/compile.ts, builder/typecheck.ts,
// builder/paths.ts, kit/plugin-kit-types.ts or the limits they read. A test rebuilds it
// and fails if the committed file is stale.
//
//   node scripts/studio/build-check-worker.mjs
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const repo = join(dirname(fileURLToPath(import.meta.url)), '..', '..')

export async function bundleCheckWorker() {
  const result = await build({
    entryPoints: [join(repo, 'src/lib/studio/builder/check-worker-entry.ts')],
    bundle: true,
    format: 'cjs',
    platform: 'node',
    target: 'node20',
    external: ['typescript'],
    legalComments: 'none',
    write: false,
    logLevel: 'error',
  })
  return result.outputFiles[0].text
}

export function generatedModule(source) {
  return `// Generated by scripts/studio/build-check-worker.mjs from builder/check-worker-entry.ts. Do not edit.\nexport const CHECK_WORKER_SOURCE = ${JSON.stringify(source)}\n`
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const source = await bundleCheckWorker()
  writeFileSync(join(repo, 'src/lib/studio/builder/check-worker.generated.ts'), generatedModule(source))
  console.log(`check worker ${(source.length / 1024).toFixed(1)} KiB`)
}
